/* Run with PLAYWRIGHT_MODULE pointing to an installed Playwright package. */
const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const url = process.env.NOW_PLAYING_TEST_URL || 'http://127.0.0.1:8081';
(async () => {
  const browser = await chromium.launch({channel: process.env.BROWSER_CHANNEL || undefined, headless: true});
  try {
    const page = await browser.newPage({viewport: {width: 1920, height: 1080}});
    let state = {status: 'idle', activity: 'listening', revision: 100, track: null};
    await page.route('**/api/state', route => route.fulfill({json: state}));
    await page.goto(url);
    await page.waitForFunction(() => !document.querySelector('#mosaic').hidden && document.querySelectorAll('.mosaic-tile img').length >= 18);
    assert.equal((await page.locator('body').innerText()).trim(), 'Listening');
    assert.equal(await page.locator('.mosaic-tile').count() <= 48, true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({path: 'output/playwright/mosaic-landscape.png'});
    const transforms = await page.locator('.mosaic-tile').evaluateAll(cells => cells.map(cell => cell.style.transform));
    await page.waitForTimeout(8500);
    assert.notDeepEqual(await page.locator('.mosaic-tile').evaluateAll(cells => cells.map(cell => cell.style.transform)), transforms);
    await page.setViewportSize({width: 1080, height: 1920});
    await page.waitForTimeout(300);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({path: 'output/playwright/mosaic-portrait.png'});
    state = {status: 'matched', activity: 'identifying', revision: 101, track: {id: 'test', title: 'Song title', artist: 'Artist', album: 'Album', artwork_url: null}};
    await page.waitForFunction(() => document.querySelector('#mosaic').hidden && !document.querySelector('#track').hidden);
    const hiddenTransforms = await page.locator('.mosaic-tile').evaluateAll(cells => cells.map(cell => cell.style.transform));
    await page.waitForTimeout(8500);
    assert.deepEqual(await page.locator('.mosaic-tile').evaluateAll(cells => cells.map(cell => cell.style.transform)), hiddenTransforms);
    assert.equal(await page.locator('#activity-text').innerText(), 'Identifying song…');
    await page.emulateMedia({reducedMotion: 'reduce'});
    state = {status: 'idle', activity: 'listening', revision: 102, track: null};
    await page.waitForFunction(() => !document.querySelector('#mosaic').hidden);
    await page.waitForTimeout(200);
    const staticTransforms = await page.locator('.mosaic-tile').evaluateAll(cells => cells.map(cell => cell.style.transform));
    await page.waitForTimeout(8500);
    assert.deepEqual(await page.locator('.mosaic-tile').evaluateAll(cells => cells.map(cell => cell.style.transform)), staticTransforms);
    const collection = await (await fetch(url + '/api/albums')).json();
    const recovery = await browser.newPage({reducedMotion: 'reduce'});
    let blocked = true;
    await recovery.route('**/api/state', route => route.fulfill({json: state}));
    await recovery.route('**/*', route => {
      const path = new URL(route.request().url()).pathname;
      return blocked && (path.startsWith('/artwork/') || path === '/demo-artwork.svg') ? route.abort() : route.continue();
    });
    await recovery.goto(url);
    await recovery.waitForFunction(() => document.querySelectorAll('.mosaic-tile').length > 0);
    await recovery.waitForTimeout(500);
    assert.equal(await recovery.locator('.mosaic-tile img').count(), 0);
    blocked = false;
    await recovery.waitForFunction(() => document.querySelectorAll('.mosaic-tile img').length > 0, {}, {timeout: 20000});
    await recovery.close();
    const partial = await browser.newPage({reducedMotion: 'reduce'});
    const badKey = 'f'.repeat(64);
    await partial.route('**/api/state', route => route.fulfill({json: state}));
    await partial.route('**/api/albums', route => route.fulfill({json: {revision: 999, albums: [{id: badKey, artwork_url: '/artwork/' + badKey}, collection.albums[0]]}}));
    await partial.route('**/artwork/' + badKey, route => route.abort());
    await partial.goto(url);
    await partial.waitForFunction(() => {
      const cells = [...document.querySelectorAll('.mosaic-tile')];
      return cells.length > 0 && cells.every(cell => cell.querySelector('img'));
    });
    await partial.close();
    const many = await browser.newPage();
    const albums = Array.from({length: 100}, (_, i) => ({id: i.toString(16).padStart(64, '0'), artwork_url: '/artwork/' + i.toString(16).padStart(64, '0')}));
    await many.route('**/api/state', route => route.fulfill({json: state}));
    await many.route('**/api/albums', route => route.fulfill({json: {revision: 1000, albums}}));
    await many.route('**/artwork/*', route => route.fulfill({contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="240" height="240"><rect width="240" height="240" fill="hsl(' + parseInt(route.request().url().slice(-4), 16) * 17 + ',40%,40%)"/></svg>'}));
    await many.goto(url);
    await many.waitForFunction(() => document.querySelectorAll('.mosaic-tile img').length >= 18);
    const initialImages = new Set(await many.locator('.mosaic-tile img').evaluateAll(images => images.map(image => image.src)));
    await many.waitForTimeout(9500);
    const laterImages = await many.locator('.mosaic-tile img').evaluateAll(images => images.map(image => image.src));
    assert.equal(laterImages.some(src => !initialImages.has(src)), true);
    assert.equal(await many.locator('.mosaic-tile').count() <= 48, true);
    await many.screenshot({path: 'output/playwright/mosaic-test-many.png'});
    await many.close();
    const interactive = await browser.newPage({viewport: {width: 1280, height: 800}, reducedMotion: 'reduce'});
    const firstId = 'a'.repeat(64), secondId = 'b'.repeat(64);
    let saved = [firstId, secondId].map((id, i) => ({id, album: 'Album ' + (i + 1), artist: 'Artist', artwork_url: '/artwork/' + id}));
    let deleteCalls = 0, failDeletion = true;
    let display = {status: 'idle', revision: 1, track: null};
    await interactive.route('**/api/state', route => route.fulfill({json: display}));
    await interactive.route('**/api/albums', route => route.fulfill({json: {revision: deleteCalls + 1, albums: saved}}));
    await interactive.route('**/api/albums/*', route => {
      assert.equal(route.request().method(), 'DELETE');
      deleteCalls++;
      if (failDeletion) return route.fulfill({status:503, json:{error:'Unavailable'}});
      saved = saved.filter(album => !route.request().url().endsWith(album.id));
      return route.fulfill({json:{deleted:true}});
    });
    await interactive.route('**/artwork/*', route => route.fulfill({contentType:'image/svg+xml', body:'<svg xmlns="http://www.w3.org/2000/svg" width="200" height="200"><rect width="200" height="200" fill="#697e64"/></svg>'}));
    await interactive.goto(url);
    await interactive.waitForFunction(() => [...document.querySelectorAll('.mosaic-tile')].every(tile => tile.querySelector('img')) && document.querySelectorAll('.mosaic-tile').length > 1);
    let first = interactive.getByRole('button', {name:'Remove Album 1 — Artist', exact:true}).first();
    await first.click();
    assert.equal(deleteCalls,0);
    assert.equal(await interactive.locator('[data-confirm]').count(),1);
    await interactive.screenshot({path:'output/playwright/album-delete-confirmation.png'});
    await interactive.keyboard.press('Escape');
    assert.equal(await interactive.locator('[data-confirm]').count(),0);
    await first.focus();
    await interactive.keyboard.press('Enter');
    assert.equal(deleteCalls,0);
    await interactive.keyboard.press('Enter');
    await interactive.getByRole('status').filter({hasText:'Could not remove album'}).waitFor();
    assert.equal(saved.length,2);
    assert.equal(await interactive.getByRole('button', {name:'Confirm removal: Album 1 — Artist', exact:true}).evaluate(button => button === document.activeElement),true,'failed keyboard confirmation retains focus');
    failDeletion = false;
    await interactive.getByRole('button', {name:'Confirm removal: Album 1 — Artist', exact:true}).click();
    await interactive.waitForFunction(() => ![...document.querySelectorAll('.mosaic-tile')].some(tile => tile.getAttribute('aria-label').includes('Album 1')));
    assert.equal(saved.length,1);
    assert.equal(deleteCalls,2);
    first = interactive.getByRole('button', {name:'Remove Album 2 — Artist', exact:true}).first();
    await first.click();
    await interactive.getByRole('button', {name:'Confirm removal: Album 2 — Artist', exact:true}).click();
    await interactive.waitForFunction(() => document.querySelectorAll('.mosaic-tile').length === 0);
    display = {status:'matched', revision:2, inferred:true, track:{title:'Current song', artist:'Artist', album:'Album', artwork_url:null}, next_track:{title:'Following song'}};
    await interactive.waitForFunction(() => document.querySelector('#title').textContent === '💿 Current song');
    assert.equal(await interactive.locator('#next-title').innerText(),'Following song');
    assert.equal(await interactive.locator('#next-song').isVisible(),true);
    await interactive.screenshot({path:'output/playwright/vinyl-next-song.png'});
    await interactive.setViewportSize({width:390,height:844});
    assert.equal(await interactive.evaluate(() => document.documentElement.scrollWidth > innerWidth),false);
    const activityBox = await interactive.locator('#activity').boundingBox();
    const nextBox = await interactive.locator('#next-song').boundingBox();
    assert.equal(activityBox.x + activityBox.width < nextBox.x,true,'bottom labels must not overlap');
    display = {status:'idle',revision:3,track:null};
    await interactive.waitForFunction(() => document.querySelector('#next-song').hidden);
    await interactive.close();
    console.log('Browser passed: album mosaic, animation, portrait/landscape, matched transition, hidden/reduced-motion pause, same-revision recovery, no broken-image holes, bounded large collections.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
